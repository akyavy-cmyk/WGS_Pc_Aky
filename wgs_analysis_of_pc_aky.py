GFF_KEYS = ["ID", "Parent", "Name", "locus_tag", "gene", "gene_biotype", "product", "protein_id",
            "pseudo", "Note", "note", "anticodon", "transl_table", "partial", "gbkey"]


def parse_attrs(s):
    d = {}
    for part in s.strip().split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            d[k] = unquote(v)
    return d


def parse_gff(path):
    recs = []
    with open_text(path) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            p = line.rstrip("\r\n").split("\t")
            if len(p) < 9:
                continue
            try:
                s, e = int(p[3]), int(p[4])
            except ValueError:
                continue
            at = parse_attrs(p[8])
            rec = {"seqid": p[0], "type": p[2], "start": s, "end": e, "strand": p[6], "phase": p[7]}
            rec.update({k: at.get(k, "") for k in GFF_KEYS})
            recs.append(rec)
    df = pd.DataFrame(recs)
    df["length"] = df["end"] - df["start"] + 1
    df["note_all"] = df["Note"].where(df["Note"] != "", df["note"])
    return df


def build_gene_table(gff):
    g = gff[gff["type"].isin(["gene", "pseudogene"])].copy()
    child = gff[gff["Parent"] != ""]
    first_child = child.drop_duplicates("Parent").set_index("Parent")
    notes = child[child["note_all"] != ""].drop_duplicates("Parent").set_index("Parent")["note_all"]
    g["child_type"] = g["ID"].map(first_child["type"]).fillna("")
    g["product"] = g["ID"].map(first_child["product"]).fillna("")
    g["note_all"] = g["note_all"].where(g["note_all"] != "", g["ID"].map(notes).fillna(""))
    g["pseudo_flag"] = (
        (g["type"] == "pseudogene")
        | (g["pseudo"].str.lower() == "true")
        | g["gene_biotype"].str.contains("pseudo", case=False)
    )
    g["class"] = np.where(g["pseudo_flag"], "pseudogene",
                          g["gene_biotype"].where(g["gene_biotype"] != "", g["child_type"].replace("", "other")))
    g["mid"] = (g["start"] + g["end"]) // 2
    return g.reset_index(drop=True)


