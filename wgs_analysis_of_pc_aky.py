def rna_analysis(gff, genes, rep, ori_ter):
    heading("4. RNA GENES, PSEUDOGENES AND SHARED PROTEIN IDS")
    lens = dict(zip(rep["seqid"], rep["length_bp"]))
    main_id = rep.iloc[0]["seqid"]

    # ---- rRNA operons
    r = gff[gff["type"] == "rRNA"].sort_values(["seqid", "start"]).copy()

    def rtype(p):
        m = re.search(r"\b(5S|16S|23S)\b", p)
        return m.group(1) if m else "other"

    r["rrna_type"] = r["product"].map(rtype)
    ops = []
    for sid, d in r.groupby("seqid"):
        cluster = []
        for _, x in d.iterrows():
            if cluster and x["start"] - cluster[-1]["end"] > 5000:
                ops.append((sid, cluster))
                cluster = []
            cluster.append(x)
        if cluster:
            ops.append((sid, cluster))
    op_rows = []
    for sid, c in ops:
        mid = (c[0]["start"] + c[-1]["end"]) // 2
        rel = np.nan
        if sid == main_id and main_id in ori_ter:
            L, ori = lens[sid], ori_ter[sid][0]
            dist = min((mid - ori) % L, (ori - mid) % L)
            rel = round(dist / (L / 2), 2)   # 0 = at oriC, 1 = at terminus
        op_rows.append({"seqid": sid, "start": c[0]["start"], "end": c[-1]["end"], "strand": c[0]["strand"],
                        "composition": "-".join(x["rrna_type"] for x in c), "n_genes": len(c),
                        "relative_distance_from_oriC": rel})
