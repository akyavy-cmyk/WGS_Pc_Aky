BASES = "TCAG"
AA_STR = "FFLLSSSSYY**CC*WLLLLPPPPHHQQRRRRIIIMTTTTNNKKSSRRVVVVAAAADDEEGGGG"
CODONS = ["".join(c) for c in itertools.product(BASES, repeat=3)]
CIDX = {c: i for i, c in enumerate(CODONS)}
CODON_AA = dict(zip(CODONS, AA_STR))
FAM = defaultdict(list)
for _c in CODONS:
    if CODON_AA[_c] != "*":
        FAM[CODON_AA[_c]].append(CIDX[_c])
CLASSES = {k: [a for a in FAM if len(FAM[a]) == k] for k in (2, 3, 4, 6)}
SENSE_MASK = np.array([CODON_AA[c] not in "*MW" for c in CODONS])
GC3_MASK = np.array([c[2] in "GC" for c in CODONS])


def extract_cds(gff, genome):
    cds = gff[gff["type"] == "CDS"].copy()
    cds["gid"] = np.where(cds["ID"] != "", cds["ID"], cds["Parent"])
    seqs, meta, skipped = [], [], Counter()
    for gid, d in cds.groupby("gid", sort=False):
        f = d.iloc[0]
        if f["pseudo"].lower() == "true":
            skipped["pseudogene"] += 1
            continue
        if "true" in f["partial"].lower():
            skipped["partial"] += 1
            continue
        if f["seqid"] not in genome:
            skipped["sequence not in fna"] += 1
            continue
        d = d.sort_values("start")
        s = "".join(genome[f["seqid"]][a - 1:b] for a, b in zip(d["start"], d["end"]))
        if f["strand"] == "-":
            s = revcomp(s)
        phase = d.iloc[0]["phase"] if f["strand"] == "+" else d.iloc[-1]["phase"]
        if phase in ("1", "2"):
            s = s[int(phase):]
        if len(s) % 3 or len(s) < 30:
            skipped["bad length"] += 1
            continue
        if s[-3:] in ("TAA", "TAG", "TGA"):
            s = s[:-3]
        seqs.append(s)
        meta.append({"gid": gid, "seqid": f["seqid"], "start": d["start"].min(), "end": d["end"].max(),
                     "strand": f["strand"], "locus_tag": f["locus_tag"], "product": f["product"]})
    return seqs, pd.DataFrame(meta), skipped


def codon_matrix(seqs):
    M = np.zeros((len(seqs), 64))
    for i, s in enumerate(seqs):
        for k in range(0, len(s) - 2, 3):
            j = CIDX.get(s[k:k + 3])
            if j is not None:
                M[i, j] += 1
    return M


def rscu(v):
    out = np.zeros(64)
    for aa, idx in FAM.items():
        tot = v[idx].sum()
        if tot > 0:
            out[idx] = v[idx] * len(idx) / tot
    return out


def enc_row(row):
    Fk = {}
    for k, aas in CLASSES.items():
        num = den = 0.0
        for a in aas:
            cnt = row[FAM[a]]
            n = cnt.sum()
            if n > 1:
                F = (n * np.sum((cnt / n) ** 2) - 1) / (n - 1)
                num += n * F
                den += n
        Fk[k] = num / den if den else np.nan
    if np.isnan(Fk[3]):
        Fk[3] = np.nanmean([Fk[2], Fk[4]])
    if any(np.isnan(v) for v in Fk.values()):
        return np.nan
    Fk = {k: max(v, 1e-3) for k, v in Fk.items()}
    return min(2 + 9 / Fk[2] + 1 / Fk[3] + 5 / Fk[4] + 3 / Fk[6], 61.0)


def codon_analysis(gff, genome, trna):
    heading("5. CODON USAGE")
    seqs, meta, skipped = extract_cds(gff, genome)
    say(f"CDS used for codon analysis: {len(seqs):,}; skipped: {dict(skipped)}")
    if len(seqs) < 20:
        say("Too few CDS for codon analysis; skipped.")
        return
    M = codon_matrix(seqs)
    meta["codons"] = M.sum(axis=1)
    meta["GC_%"] = [round(gc_frac(s) * 100, 2) for s in seqs]
    sense = M[:, SENSE_MASK].sum(axis=1)
    meta["GC3s_%"] = np.where(sense > 0, M[:, SENSE_MASK & GC3_MASK].sum(axis=1) / np.maximum(sense, 1) * 100, np.nan)
    ok = (meta["codons"] >= MIN_CODONS_PER_GENE).values
    meta["ENC"] = [enc_row(M[i]) if ok[i] else np.nan for i in range(len(seqs))]

    ribo = meta["product"].str.contains(r"ribosomal protein", case=False, regex=True).values.copy()
    ribo &= ok
    tot_rscu = rscu(M.sum(axis=0))
    table = pd.DataFrame({"codon": CODONS, "aa": [CODON_AA[c] for c in CODONS],
                          "count": M.sum(axis=0).astype(int), "RSCU_all": tot_rscu.round(3)})
    table["fraction_%"] = (table["count"] / table["count"].sum() * 100).round(3)

    if ribo.sum() >= 10:
        r_rscu = rscu(M[ribo].sum(axis=0))
        table["RSCU_ribosomal"] = r_rscu.round(3)
        w = np.ones(64)
        for aa, idx in FAM.items():
            mx = r_rscu[idx].max()
            if mx > 0:
                w[idx] = np.maximum(r_rscu[idx] / mx, 0.01)
        lw = np.log(w) * SENSE_MASK
        meta["CAI"] = np.exp((M * lw).sum(axis=1) / np.maximum((M[:, SENSE_MASK]).sum(axis=1), 1))
    else:
        meta["CAI"] = np.nan
        say("  <10 ribosomal-protein genes found; CAI skipped.")
    save_table(table, "05_codon_usage_table.csv")

    z = (meta["GC3s_%"] - meta["GC3s_%"].mean()) / meta["GC3s_%"].std()
    meta["GC3s_zscore"] = z.round(2)
    meta["atypical_GC3"] = z.abs() > 2
    meta["ribosomal"] = ribo
    save_table(meta.drop(columns=["gid"]), "05_gene_codon_metrics.csv")
    save_table(meta[meta["atypical_GC3"]].sort_values("GC3s_zscore", key=abs, ascending=False)
               .drop(columns=["gid"]), "05_atypical_genes.csv")

    say(f"Mean GC of CDS: {meta['GC_%'].mean():.1f}%; mean GC3s: {meta['GC3s_%'].mean():.1f}%")
    say(f"Mean ENC: {meta['ENC'].mean():.1f}" + (f"; ribosomal genes ENC {meta.loc[ribo, 'ENC'].mean():.1f}" if ribo.any() else ""))
    say(f"Atypical genes (|GC3s z| > 2): {int(meta['atypical_GC3'].sum())} "
        f"({meta['atypical_GC3'].mean() * 100:.1f}%) - candidates for horizontally transferred DNA")

    fig, ax = plt.subplots(1, 3, figsize=(17, 4.5))
    ax[0].scatter(meta["GC3s_%"], meta["GC_%"], s=4, c=np.where(meta["atypical_GC3"], "red", "steelblue"), alpha=0.6)
    ax[0].set_xlabel("GC3s (%)")
    ax[0].set_ylabel("Gene GC (%)")
    ax[0].set_title("GC vs GC3s (red = atypical)")
    s = np.linspace(0.01, 0.99, 200)
    ax[1].plot(s * 100, 2 + s + 29 / (s ** 2 + (1 - s) ** 2), "k--", lw=1, label="Expected (no selection)")
    ax[1].scatter(meta["GC3s_%"], meta["ENC"], s=4, alpha=0.5, label="genes")
    if ribo.any():
        ax[1].scatter(meta.loc[ribo, "GC3s_%"], meta.loc[ribo, "ENC"], s=14, color="red", label="ribosomal")
    ax[1].set_xlabel("GC3s (%)")
    ax[1].set_ylabel("ENC")
    ax[1].set_title("Wright plot")
    ax[1].legend(fontsize=8)
    if meta["CAI"].notna().any():
        ax[2].hist(meta["CAI"].dropna(), bins=50, color="grey")
        if ribo.any():
            ax[2].hist(meta.loc[ribo, "CAI"], bins=20, color="red", alpha=0.7, label="ribosomal")
            ax[2].legend()
        ax[2].set_title("CAI (reference = ribosomal genes)")
        ax[2].set_xlabel("CAI")
    save_fig(fig, "05_codon_usage.png")

    # tRNA supply vs codon demand
    if trna is not None and len(trna):
        aa_tot = pd.Series({aa: M.sum(axis=0)[idx].sum() for aa, idx in FAM.items()})
        demand = (aa_tot / aa_tot.sum() * 100).rename("codon_demand_%")
        supply = trna.dropna(subset=["aa1"]).groupby("aa1").size().rename("tRNA_genes")
        anti = trna.dropna(subset=["aa1"]).groupby("aa1")["anticodon_seq"].agg(
            lambda x: ",".join(sorted(set(v for v in x if v)))).rename("anticodons")
        comp = pd.concat([demand, supply, anti], axis=1).fillna({"tRNA_genes": 0, "anticodons": ""})
        comp["tRNA_genes"] = comp["tRNA_genes"].astype(int)
        comp = comp.loc[[a for a in "ACDEFGHIKLMNPQRSTVWY" if a in comp.index]]
        save_table(comp.reset_index().rename(columns={"index": "aa"}), "05_trna_vs_codon_demand.csv")
        rx, ry = comp["codon_demand_%"].rank(), comp["tRNA_genes"].rank()
        rho = np.corrcoef(rx, ry)[0, 1]
        say(f"\nSpearman correlation, tRNA gene copies vs amino-acid demand: {rho:.2f}")
        fig, ax = plt.subplots(1, 2, figsize=(13, 4.5))
        ax[0].bar(comp.index, comp["tRNA_genes"], color="seagreen")
        ax[0].set_title("tRNA gene copies per amino acid")
        ax[1].scatter(comp["codon_demand_%"], comp["tRNA_genes"], color="seagreen")
        for aa, row in comp.iterrows():
            ax[1].annotate(aa, (row["codon_demand_%"], row["tRNA_genes"]), fontsize=8, xytext=(3, 3),
                           textcoords="offset points")
        ax[1].set_xlabel("Amino-acid usage in CDS (%)")
        ax[1].set_ylabel("tRNA gene copies")
        ax[1].set_title(f"tRNA supply vs demand (Spearman r = {rho:.2f})")
        save_fig(fig, "05_trna_vs_demand.png")


