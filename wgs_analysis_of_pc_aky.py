def is_leading(mid, strand, ori, ter, L):
    first_arc = ((mid - ori) % L) <= ((ter - ori) % L)
    return (strand == "+") == first_arc


def gene_structure(genes, gff, rep, ori_ter):
    heading("3. GENE STRUCTURE (GFF)")
    comp = genes["class"].value_counts().rename_axis("gene_class").reset_index(name="count")
    comp["percent"] = (comp["count"] / comp["count"].sum() * 100).round(2)
    save_table(comp, "03_gene_classes.csv")
    say(f"Total genes (incl. pseudogenes): {len(genes):,}")
    show(comp)

    lens = {r["seqid"]: r["length_bp"] for _, r in rep.iterrows()}
    rows = []
    for sid, d in genes.groupby("seqid"):
        L = lens.get(sid, np.nan)
        cds = gff[(gff["seqid"] == sid) & (gff["type"] == "CDS")]
        rows.append({
            "seqid": sid, "length_bp": L, "genes": len(d),
            "genes_per_Mb": round(len(d) / L * 1e6, 1) if L else np.nan,
            "genic_fraction_%": round(merged_length(d["start"], d["end"]) / L * 100, 2) if L else np.nan,
            "CDS_fraction_%": round(merged_length(cds["start"], cds["end"]) / L * 100, 2) if L and len(cds) else 0,
            "plus_strand": int((d["strand"] == "+").sum()),
            "minus_strand": int((d["strand"] == "-").sum()),
        })
    per_rep = pd.DataFrame(rows).sort_values("length_bp", ascending=False)
    save_table(per_rep, "03_per_replicon_gene_stats.csv")
    show(per_rep)

    # Intergenic gaps and overlaps
    gaps = []
    for sid, d in genes.sort_values(["seqid", "start"]).groupby("seqid"):
        s, e, st = d["start"].values, d["end"].values, d["strand"].values
        if len(s) < 2:
            continue
        prev_end = np.maximum.accumulate(e)[:-1]
        gaps.append(pd.DataFrame({"seqid": sid, "gap": s[1:] - prev_end - 1, "same_strand": st[1:] == st[:-1]}))
    gaps = pd.concat(gaps) if gaps else pd.DataFrame(columns=["seqid", "gap", "same_strand"])
    overl = gaps[gaps["gap"] < 0]["gap"].value_counts().head(6)
    say(f"\nOverlapping neighbouring genes: {int((gaps['gap'] < 0).sum()):,} "
        f"({(gaps['gap'] < 0).mean() * 100:.1f}%). Most common overlaps (bp): "
        + ", ".join(f"{-k} bp x{v}" for k, v in overl.items()))
    say(f"Median intergenic gap: {gaps['gap'].median():.0f} bp; "
        f"adjacent genes on the same strand: {gaps['same_strand'].mean() * 100:.1f}%")

    # Leading / lagging strand
    lead_info = None
    main_id = rep.iloc[0]["seqid"]
    if main_id in ori_ter:
        ori, ter = ori_ter[main_id]
        d = genes[(genes["seqid"] == main_id) & (genes["class"] != "pseudogene")].copy()
        d["leading"] = [is_leading(m, s, ori, ter, lens[main_id]) for m, s in zip(d["mid"], d["strand"])]
        lead_info = d
        pc = d[d["class"] == "protein_coding"]
        say(f"Protein-coding genes on the leading strand: {pc['leading'].mean() * 100:.1f}% "
            f"({int(pc['leading'].sum()):,} of {len(pc):,})")
        for cls in ("rRNA", "tRNA"):
            x = d[d["class"] == cls]
            if len(x):
                say(f"{cls} genes on the leading strand: {x['leading'].mean() * 100:.1f}% ({int(x['leading'].sum())} of {len(x)})")

    # Plots
    fig, ax = plt.subplots(1, 4, figsize=(18, 4))
    pc = genes[genes["class"] == "protein_coding"]
    ax[0].hist(pc["length"], bins=60, color="steelblue")
    ax[0].axvline(pc["length"].median(), color="red", ls="--")
    ax[0].set_title(f"Protein-coding gene length (median {pc['length'].median():.0f} bp)")
    ax[0].set_xlabel("bp")
    ax[1].hist(gaps["gap"].clip(-60, 600), bins=70, color="darkorange")
    ax[1].set_title("Intergenic distance (negative = overlap)")
    ax[1].set_xlabel("bp (clipped to -60..600)")
    top = comp.head(8)
    ax[2].barh(top["gene_class"][::-1], top["count"][::-1], color="seagreen")
    ax[2].set_xscale("log")
    ax[2].set_title("Gene classes (log scale)")
    if lead_info is not None:
        cats = ["protein_coding", "rRNA", "tRNA", "pseudogene"]
        allg = genes[genes["seqid"] == main_id].copy()
        allg["leading"] = [is_leading(m, s, *ori_ter[main_id], lens[main_id]) for m, s in zip(allg["mid"], allg["strand"])]
        pct = [allg[allg["class"] == c]["leading"].mean() * 100 if (allg["class"] == c).any() else np.nan for c in cats]
        ax[3].bar(cats, pct, color="slateblue")
        ax[3].axhline(50, color="grey", ls="--")
        ax[3].set_ylabel("% on leading strand")
        ax[3].set_title("Leading-strand bias")
        ax[3].tick_params(axis="x", rotation=30)
    else:
        ax[3].bar(per_rep["seqid"].head(8), per_rep["plus_strand"].head(8), label="+")
        ax[3].bar(per_rep["seqid"].head(8), per_rep["minus_strand"].head(8),
                  bottom=per_rep["plus_strand"].head(8), label="-")
        ax[3].legend()
        ax[3].set_title("Genes per strand")
        ax[3].tick_params(axis="x", rotation=60)
    save_fig(fig, "03_gene_structure.png")
    return comp, gaps


