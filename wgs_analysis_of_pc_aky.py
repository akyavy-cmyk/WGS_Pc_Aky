def read_fasta(path):
    seqs, headers, name, buf = {}, {}, None, []
    with open_text(path) as f:
        for line in f:
            line = line.rstrip()
            if line.startswith(">"):
                if name is not None:
                    seqs[name] = "".join(buf)
                headers[line[1:].split()[0]] = line[1:]
                name = line[1:].split()[0]
                buf = []
            elif name is not None:
                buf.append(line.strip())
    if name is not None:
        seqs[name] = "".join(buf)
    return seqs, headers


