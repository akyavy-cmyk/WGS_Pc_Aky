def gc_frac(s):
    g, c = s.count("G") + s.count("C"), s.count("A") + s.count("T")
    return g / (g + c) if (g + c) else float("nan")


def n50(lengths):
    lengths = sorted(lengths, reverse=True)
    half, acc = sum(lengths) / 2, 0
    for x in lengths:
        acc += x
        if acc >= half:
            return x
    return 0


def merged_length(starts, ends):
    iv = sorted(zip(starts, ends))
    total, cur_s, cur_e = 0, None, None
    for s, e in iv:
        if cur_e is None or s > cur_e + 1:
            if cur_e is not None:
                total += cur_e - cur_s + 1
            cur_s, cur_e = s, e
        else:
            cur_e = max(cur_e, e)
    if cur_e is not None:
        total += cur_e - cur_s + 1
    return total


