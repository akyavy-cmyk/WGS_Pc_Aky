def parse_assembly_report(path):
    meta, header, rows = {}, None, []
    with open_text(path) as f:
        for line in f:
            line = line.rstrip("\r\n")
            if line.startswith("# Sequence-Name"):
                header = line[1:].strip().split("\t")
            elif line.startswith("#"):
                m = re.match(r"#\s*([^:]+):\s*(.*)$", line)
                if m:
                    meta[m.group(1).strip()] = m.group(2).strip()
            elif line.strip():
                rows.append(line.split("\t"))
    tbl = pd.DataFrame(rows)
    if header and not tbl.empty and tbl.shape[1] == len(header):
        tbl.columns = header
    return meta, tbl


def replicon_table(genome, report_tbl):
    info = {}
    if report_tbl is not None and not report_tbl.empty:
        for _, r in report_tbl.iterrows():
            for col in ("RefSeq-Accn", "GenBank-Accn", "Sequence-Name"):
                if col in report_tbl.columns:
                    info[str(r[col])] = r
    rows = []
    for sid, seq in genome.items():
        acgt = sum(seq.count(b) for b in "ACGT")
        r = info.get(sid)
        rows.append({
            "seqid": sid,
            "name": r.get("Sequence-Name", "") if r is not None else "",
            "type": r.get("Assigned-Molecule-Location/Type", "") if r is not None else "",
            "length_bp": len(seq),
            "GC_percent": round(gc_frac(seq) * 100, 2),
            "N_count": seq.count("N"),
            "other_ambiguous": len(seq) - acgt - seq.count("N"),
        })
    return pd.DataFrame(rows).sort_values("length_bp", ascending=False).reset_index(drop=True)


