def circular_map(sid, seq, genes, ori_ter, organism, fname):
    L = len(seq)
    pos, gc, skew = window_stats(seq, max(auto_window(L) // 2, 200))
    tw = 2 * np.pi / L
    fig = plt.figure(figsize=(9, 9))
    ax = fig.add_subplot(111, projection="polar")
    ax.set_theta_zero_location("N")
    ax.set_theta_direction(-1)

    def ring(d, r0, r1, color):
        if len(d):
            width = np.maximum((d["end"].values - d["start"].values + 1) * tw, 2 * np.pi / 2500)
            ax.bar(d["start"].values * tw, r1 - r0, width=width, bottom=r0, align="edge",
                   color=color, linewidth=0)

    g = genes[genes["seqid"] == sid]
    pc = g[~g["class"].isin(["pseudogene", "rRNA", "tRNA"])]
    ring(pc[pc["strand"] == "+"], 8.6, 9.5, "#3b6fb6")
    ring(pc[pc["strand"] == "-"], 7.7, 8.6, "#d1495b")
    ring(g[g["class"] == "pseudogene"], 7.7, 9.5, "#f4a259")
    ring(g[g["class"] == "tRNA"], 9.6, 10.3, "#2a9d8f")
    ring(g[g["class"] == "rRNA"], 9.6, 10.6, "black")

    for base, vals, label in ((6.4, (gc - np.nanmean(gc)), "GC"), (4.8, np.nan_to_num(skew), "skew")):
        amp = np.nanmax(np.abs(vals)) or 1
        r = base + vals / amp * 0.9
        th = pos * tw
        ax.plot(np.linspace(0, 2 * np.pi, 300), np.full(300, base), color="grey", lw=0.4)
        ax.fill_between(th, base, r, where=vals >= 0, color="#1b9e77", alpha=0.8, interpolate=True)
        ax.fill_between(th, base, r, where=vals < 0, color="#7570b3", alpha=0.8, interpolate=True)

    if sid in ori_ter:
        for p, lab, col in ((ori_ter[sid][0], "oriC", "red"), (ori_ter[sid][1], "ter", "blue")):
            ax.plot([p * tw] * 2, [3.8, 10.8], color=col, ls="--", lw=1)
            ax.text(p * tw, 11.2, lab, color=col, ha="center", fontsize=9)

    step = 10 ** int(math.floor(math.log10(L / 6)))
    step = step * (5 if L / step > 12 else 2 if L / step > 8 else 1) if step else 1
    ticks = np.arange(step, L, step)   # starts at 'step' so no "0.00 Mb" label is drawn
    ax.set_xticks(ticks * tw)
    ax.set_xticklabels([f"{t / 1e6:.2f} Mb" if L > 1e6 else f"{t / 1e3:.0f} kb" for t in ticks], fontsize=8)
    ax.set_yticks([])
    ax.set_ylim(0, 11.5)
    ax.grid(False)
    ax.spines["polar"].set_visible(False)
    ax.text(0, 0, f"{organism}\n{sid}\n{L:,} bp\nGC {gc_frac(seq) * 100:.1f}%\n{len(g):,} genes",
            ha="center", va="center", fontsize=10)
    from matplotlib.patches import Patch
    ax.legend(handles=[Patch(color="#3b6fb6", label="CDS +"), Patch(color="#d1495b", label="CDS -"),
                       Patch(color="black", label="rRNA"), Patch(color="#2a9d8f", label="tRNA"),
                       Patch(color="#f4a259", label="pseudogene"),
                       Patch(color="#1b9e77", label="GC / skew above mean"),
                       Patch(color="#7570b3", label="below mean")],
              loc="lower left", bbox_to_anchor=(-0.12, -0.08), fontsize=8, frameon=False)
    ax.set_title("Circular genome map (outer to inner: RNA, CDS +, CDS -, GC content, GC skew)", fontsize=10, pad=20)
    save_fig(fig, fname)


